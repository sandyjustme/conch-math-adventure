/**
 * 短剧世界观 + 预写剧集（纯数据）。
 *
 * 设计铁律（改任何一集之前先读）：
 *   1. choice.prompt 是「主角必须做的决定」，不是旁白提问 —— 禁止"请问/计算/答案是/等于"
 *   2. 题面不许出现数学术语 —— 负数/正数/绝对值/相反数/比大小/加减乘除/数轴
 *   3. optionA/optionB 必须是剧情动作，不能是裸数字
 *   4. branchWrong 必须继续推进剧情，并在其中把正确逻辑说破（教学发生在这里）
 *   5. 一集只考一个知识点
 *
 * 校验器 engine/validateDrama.ts 会在开发期强制这五条。
 */

export interface EpisodeChoice {
  /** 主角必须做的决定 */
  prompt: string;
  /** 剧情动作，不是裸数字 */
  optionA: string;
  optionB: string;
  correct: "A" | "B";
}

export interface Episode {
  /** 集号，从 1 开始，全局连续 */
  no: number;
  /** 季号，从 1 开始 */
  season: number;
  title: string;
  /** 本集考的知识点；无题集为 null */
  nodeId: string | null;
  /** 接住上集钩子，只回应一半 */
  openText: string;
  /** 推进到困境 */
  bodyText: string;
  /** 无题集为 null，此时直接走 hookText */
  choice: EpisodeChoice | null;
  branchRight: string;
  branchWrong: string;
  /** 集末钩子，不以句号结尾 */
  hookText: string;
}

